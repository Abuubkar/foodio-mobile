/* Regenerates data.js from mocks/db.json.
   Run from the repository root: node mockups/clips-directions/data.gen.cjs

   CommonJS on purpose: package.json declares "type": "module", so a .js file
   here would be parsed as ESM and `require` would throw.

   The other mockups keep data.js by hand. This one does not, because the
   pairing variant depends on which dishes have both a restaurant clip and a
   customer one — a fact about the seed that quietly changes under you. */

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..', '..');
const db = JSON.parse(fs.readFileSync(path.join(root, 'mocks', 'db.json'), 'utf8'));

const itemById = Object.fromEntries(db.menuItems.map((m) => [m.id, m]));
const restById = Object.fromEntries(db.restaurants.map((r) => [r.id, r]));
const personById = Object.fromEntries(db.people.map((p) => [p.id, p]));

const shape = (c) => {
  const item = c.menuItemId ? itemById[c.menuItemId] : null;
  const r = restById[c.restaurantId];

  return {
    id: c.id,
    kind: c.author.kind,
    person: c.author.personId ? (personById[c.author.personId]?.displayName ?? null) : null,
    orderId: c.author.orderId ?? null,
    restaurantId: c.restaurantId,
    restaurantName: c.restaurantName,
    caption: c.caption,
    media: c.mediaUrl,
    poster: c.thumbnailUrl,
    seconds: c.durationSeconds,
    postedAt: c.postedAt,
    menuItemId: c.menuItemId ?? null,
    dish: item
      ? {
          id: item.id,
          name: item.name,
          priceMinor: item.priceMinor,
          rating: item.rating ?? null,
          image: item.image,
          optionGroups: (item.optionGroups ?? []).map((g) => g.name),
        }
      : null,
    restaurant: r
      ? {
          cuisines: r.cuisines,
          rating: r.rating,
          reviewCount: r.reviewCount,
          deliveryFeeMinor: r.deliveryFeeMinor,
          currency: r.currency,
          minMinutes: r.deliveryEstimate.minMinutes,
          maxMinutes: r.deliveryEstimate.maxMinutes,
          image: r.image,
        }
      : null,
  };
};

const clips = db.clips.map(shape);

/** Dishes with both sides of the argument. Variant A can render nothing else. */
const pairs = [];
for (const sold of clips.filter((c) => c.kind === 'restaurant' && c.menuItemId)) {
  const ours = clips.find((c) => c.kind === 'customer' && c.menuItemId === sold.menuItemId);
  if (ours) pairs.push({ menuItemId: sold.menuItemId, dish: sold.dish, ours, sold });
}

/* A kitchen is a restaurant that has at least one clip, carrying its whole
   menu. The chapter variants need this: a restaurant has six to ten dishes
   and only one or two of them were ever filmed, which is the real shape of
   the problem. Faking chapters out of four different restaurants — as S did —
   hides exactly the case that breaks. */
const catsFor = (restaurantId) =>
  db.menuCategories
    .filter((c) => c.restaurantId === restaurantId)
    .sort((a, b) => a.position - b.position);

const kitchens = [];
for (const r of db.restaurants) {
  const mine = clips.filter((c) => c.restaurantId === r.id);
  if (!mine.length) continue;

  const clipFor = (itemId) => mine.find((c) => c.menuItemId === itemId) ?? null;

  kitchens.push({
    id: r.id,
    name: r.name,
    restaurant: shape({ ...db.clips.find((c) => c.restaurantId === r.id), menuItemId: null })
      .restaurant,
    /* The restaurant's own footage first; a customer's receipt is a different
       argument and should not open the kitchen. */
    clips: [
      ...mine.filter((c) => c.kind === 'restaurant'),
      ...mine.filter((c) => c.kind === 'customer'),
    ],
    menu: catsFor(r.id).map((cat) => ({
      name: cat.name,
      items: db.menuItems
        .filter((m) => m.menuCategoryId === cat.id)
        .map((m) => ({
          id: m.id,
          name: m.name,
          priceMinor: m.priceMinor,
          image: m.image,
          popular: m.isPopular ?? false,
          optionGroups: (m.optionGroups ?? []).map((g) => g.name),
          clipId: clipFor(m.id)?.id ?? null,
        })),
    })),
  });
}

fs.writeFileSync(
  path.join(__dirname, 'data.js'),
  '/* THROWAWAY PROTOTYPE DATA — generated by data.gen.js from mocks/db.json.\n' +
    '   Do not edit by hand; regenerate instead. */\n' +
    'window.FOODIO_CLIPS = ' +
    JSON.stringify({ clips, pairs, kitchens }, null, 2) +
    ';\n',
);

console.log(`clips: ${clips.length} | paired dishes: ${pairs.length}`);
console.log(`pairs: ${pairs.map((p) => p.dish.name).join(', ')}`);
console.log(
  `kitchens: ${kitchens
    .map((k) => {
      const items = k.menu.flatMap((c) => c.items);
      return `${k.name} (${k.clips.length} clips / ${items.length} dishes)`;
    })
    .join(', ')}`,
);
